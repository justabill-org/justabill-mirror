test("adds this device's votes, votes into the account, downloads the data and deletes the account", async ({
  page,
}) => {
  // Signed out, the vote stays on this device (#72).
  await voteYeaOnHouseBill(page);
  await expect(page.getByText("Kept on this device only. Your vote isn't sent anywhere.")).toBeVisible();

  const votePosts: { url: string; auth: string | undefined }[] = [];
  page.on("request", (r) => {
    if (r.method() === "POST" && /\/api\/v1\/(bills\/[^/]+\/vote|me\/votes:import)$/.test(new URL(r.url()).pathname)) {
      votePosts.push({ url: new URL(r.url()).pathname, auth: r.headers()["authorization"] });
    }
  });

  await signInNewAccount(page, `/bills/${SENATE_BILL.id}`);

  // Onboarding offers the device's vote, and sends nothing until asked.
  await expect(page.getByText("You voted on 1 bill before signing in.", { exact: false })).toBeVisible();
  expect(votePosts).toEqual([]);
  await expectBothSchemesAccessible(page, "onboarding with the offer to add this device's votes");
  await page.getByRole("button", { name: "Add 1 vote to my account" }).click();
  await expect(page.getByText("Added 1 vote to your account.")).toBeVisible();
  await page.getByRole("button", { name: "Continue" }).click();
  await expect(page).toHaveURL(new RegExp(`/bills/${SENATE_BILL.id}$`));

  // Signed in, a vote goes to the account with the token, and there's no "this device" note. The
  // button shows the choice while it saves, so wait for the API's answer.
  const cast = page.waitForResponse((r) => r.request().method() === "POST" && r.url().endsWith(`/bills/${SENATE_BILL.id}/vote`));
  await page.getByRole("button", { name: "Nay", exact: true }).click();
  expect((await cast).status()).toBe(200);
  await expect(page.getByRole("button", { name: "Nay", exact: true })).toHaveAttribute("aria-pressed", "true");
  expect(votePosts.map((p) => p.url)).toEqual(["/api/v1/me/votes:import", `/api/v1/bills/${SENATE_BILL.id}/vote`]);
  for (const p of votePosts) expect(p.auth).toMatch(/^Bearer /);
  await expect(page.getByText(/Kept on this device/)).toHaveCount(0);

  // The imported vote shows from the account, and the device copy is gone.
  await page.goto(`/bills/${HOUSE_BILL.id}`);
  await expect(page.getByRole("button", { name: "Yea", exact: true })).toHaveAttribute("aria-pressed", "true");
  expect(await page.evaluate(() => localStorage.getItem("jab.votes.v1"))).not.toContain(HOUSE_BILL.id);

  // Download my data is exactly what the API keeps.
  await page.goto("/settings");
  const downloading = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download my data" }).click();
  const download = await downloading;
  expect(download.suggestedFilename()).toBe("just-a-bill-account.json");
  const data = JSON.parse(await readFile((await download.path())!, "utf8")) as {
    votes: { bill_id: string; vote: string }[];
  };
  expect(data.votes.map((v) => [v.bill_id, v.vote]).sort()).toEqual([
    [HOUSE_BILL.id, "yea"],
    [SENATE_BILL.id, "nay"],
  ]);

  // Deleting it signs out; the sign-in just now is recent enough for the API.
  const deleted = page.waitForResponse((r) => r.request().method() === "DELETE" && new URL(r.url()).pathname === "/api/v1/me");
  await page.getByRole("button", { name: "Delete my account" }).click();
  await expectBothSchemesAccessible(page, "settings with the deletion confirmation open");
  await page.getByRole("group").getByRole("button", { name: "Delete my account" }).click();
  expect((await deleted).status()).toBe(204);
  await expect(page.getByText("Sign in to see your settings")).toBeVisible();
});

test("follows a bill, sees it in settings and unfollows it", async ({ page, request }) => {
  test.setTimeout(120_000);
  await startFreshAccountWindow(request);

  // Signed out, a bill page has no Follow button: nothing but votes is kept (#282).
  await page.goto(`/bills/${HOUSE_BILL.id}`);
  await expect(page.getByRole("button", { name: "Yea", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: /^Follow/ })).toHaveCount(0);

  await signInNewAccount(page, `/bills/${HOUSE_BILL.id}`);
  await expect(page).toHaveURL(/\/signup\?/);
  await page.getByRole("button", { name: "Continue" }).click();
  await expect(page).toHaveURL(new RegExp(`/bills/${HOUSE_BILL.id}$`));

  const followed = page.waitForResponse((r) => r.request().method() === "POST" && r.url().endsWith(`/me/favorites/${HOUSE_BILL.id}`));
  await page.getByRole("button", { name: "Follow", exact: true }).click();
  expect((await followed).status()).toBe(200);
  await expect(page.getByRole("button", { name: "Following" })).toHaveAttribute("aria-pressed", "true");

  // The state comes from the account: it survives a reload.
  await page.reload();
  await expect(page.getByRole("button", { name: "Following" })).toBeVisible();

  await page.goto("/settings");
  await expect(page.getByRole("link", { name: HOUSE_BILL.label })).toHaveAttribute("href", `/bills/${HOUSE_BILL.id}`);
  await expectBothSchemesAccessible(page, "settings with a followed bill");
  await page.getByRole("button", { name: `Unfollow ${HOUSE_BILL.label}` }).click();
  await expect(page.getByText("You don't follow any bills yet.")).toBeVisible();

  await page.goto(`/bills/${HOUSE_BILL.id}`);
  await expect(page.getByRole("button", { name: "Follow", exact: true })).toHaveAttribute("aria-pressed", "false");
});

// The Privacy page: a visitor who doesn't sign in loads no third-party scripts. Firebase Auth's
// initialization loads Google's sign-in helper (gapi) on phones and Safari, so the store loads
// Firebase only once someone presses sign-in or has signed in on this device (#757).
test.describe("on an iPhone", () => {
  test.use(iPhone);

  test("a visitor who never signed in loads nothing from apis.google.com and no auth iframe", async ({ page }) => {
    const google: string[] = [];
    await page.route(/^https:\/\/apis\.google\.com\//, (route) => {
      google.push(route.request().url());
      return route.abort();
    });

    await page.goto("/");
    // The Sign in link shows once the auth store knows nobody is signed in (it's in the DOM, though
    // hidden on a phone, outside the menu).
    await expect(page.locator('header a[href="/login"]').first()).toBeAttached();
    await page.goto("/login");
    await expect(page.getByRole("button", { name: "Continue with Google" })).toBeEnabled();
    // Without the fix the store reports signed out only after Firebase's initialization, which has
    // already asked for gapi by then; the grace period covers anything a late script would load.
    await page.waitForLoadState("load");
    await page.waitForTimeout(1_000);

    expect(google).toEqual([]);
    expect(page.frames().map((f) => f.url()).filter(isAuthIframe)).toEqual([]);
  });

  test("signs in with a redirect, and Firebase loads on later pages", async ({ page }) => {
    await page.goto("/login?next=/settings");
    await page.getByRole("button", { name: "Continue with Google" }).click();

    // The emulator's Google page, in this tab instead of a popup.
    await page.waitForURL(/\/emulator\/auth\/handler/);
    const autoGenerate = page.getByRole("button", { name: "Auto-generate user information" });
    await expect(async () => {
      if (!(await autoGenerate.isVisible())) await page.getByText("Add new account").click({ timeout: 1_000 });
      await expect(autoGenerate).toBeVisible({ timeout: 1_000 });
    }).toPass({ timeout: 15_000 });
    await autoGenerate.click();
    await page.getByRole("button", { name: /Sign in with Google/ }).click();

    // Back on /login, the store loads Firebase to finish the sign-in, then onboarding comes.
    await expect(page).toHaveURL(/\/signup\?next=%2Fsettings$/, { timeout: 30_000 });
    await page.getByRole("button", { name: "Continue" }).click();
    await expect(page).toHaveURL(/\/settings$/);

    // A new page load follows the session, because someone signed in here.
    await page.goto("/");
    await expect(page.locator('header a[href="/settings"]').first()).toBeAttached();
  });
});
