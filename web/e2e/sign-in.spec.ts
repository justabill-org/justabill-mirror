// Sign-in (#137, docs/design/55-social-auth.md "Testing"): the real sign-in page and Firebase JS
// SDK against the Firebase Auth emulator, and the API verifying the emulator's ID tokens. It needs
// the emulator and a web build with accounts on, so it runs under `task e2e:sign-in`
// (E2E_AUTH_EMULATOR_HOST set) and is skipped otherwise. #250 adds it to CI.
//
// Only the first two tests sign in through the emulator's Google popup, which depends on a script
// from apis.google.com (#777); the others start from a session the emulator minted (seedSession) and
// visit /login with it, so the page still reads or creates the account and runs onboarding.

test.skip(!process.env.E2E_AUTH_EMULATOR_HOST, "needs the Auth emulator: task e2e:sign-in");
test.describe.configure({ timeout: SIGN_IN_TEST_TIMEOUT });

/** Finishes the emulator's fake Google popup as a new, auto-generated user. */
async function autoGeneratedUser(popup: Page) {
  // Once earlier tests have made accounts, the emulator lists them first, and it renders that list
  // after load, which can swallow a click on "Add new account". Click until the form shows.
  const autoGenerate = popup.getByRole("button", { name: "Auto-generate user information" });
  await expect(async () => {
    if (!(await autoGenerate.isVisible())) await popup.getByText("Add new account").click({ timeout: 1_000 });
    await expect(autoGenerate).toBeVisible({ timeout: 1_000 });
  }).toPass({ timeout: 15_000 });
  await autoGenerate.click();
  await popup.getByRole("button", { name: /Sign in with Google/ }).click();
}

/** Visits /login?next= as a new account with a seeded session: the page then goes on by itself. */
async function signInNewAccount(page: Page, next: string) {
  await seedSession(page, uniqueSubject());
  await page.goto(`/login?next=${encodeURIComponent(next)}`);
}

